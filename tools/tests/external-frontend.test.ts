// HOOK(external-frontend): tests for feeding the engine Raw IR produced by a
// non-TypeScript frontend — the versioned envelope, `*.rawir.json` input, the
// `frontends` config key, pre-parsed spec expressions, and the floor
// division/modulo binops.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { parseExpr } from "../src/specparser.ts";

const cli = fileURLToPath(new URL("../src/lsc.ts", import.meta.url));
const examples = fileURLToPath(new URL("../../examples/", import.meta.url));
const loader = createRequire(import.meta.url).resolve("tsx");

function lsc(args: string[], cwd: string) {
  const result = spawnSync(process.execPath, ["--import", loader, cli, ...args], {
    cwd, env: { ...process.env, LSC_RUN_LOG: "false" }, encoding: "utf8", timeout: 60_000,
  });
  assert.ifError(result.error);
  return result;
}

function withDir<T>(f: (dir: string) => T): T {
  const dir = realpathSync(mkdtempSync(join(tmpdir(), "lsc-external-frontend-")));
  try { return f(dir); } finally { rmSync(dir, { recursive: true, force: true }); }
}

function extractRaw(tsFile: string): any {
  const r = lsc(["extract", join(examples, tsFile)], examples);
  assert.equal(r.status, 0, r.stderr);
  return JSON.parse(r.stdout);
}

function envelope(module: unknown, extra: Record<string, unknown> = {}) {
  return { format: "lemmascript-raw-ir", version: 1, producer: { name: "test", version: "0" }, module, ...extra };
}

/** Generated text minus the provenance header line, which names the source file. */
function body(dfy: string): string {
  return dfy.split("\n").filter(l => !l.startsWith("// Generated by lsc from")).join("\n");
}

test("a *.rawir.json envelope generates the same Dafny as the TS source", () => {
  const raw = extractRaw("clamp.ts");
  withDir(dir => {
    writeFileSync(join(dir, "clamp.rawir.json"), JSON.stringify(envelope(raw)));
    const r = lsc(["gen", "--backend=dafny", "clamp.rawir.json"], dir);
    assert.equal(r.status, 0, r.stderr);
    const got = readFileSync(join(dir, "clamp.dfy.gen"), "utf8");
    const want = readFileSync(join(examples, "clamp.dfy.gen"), "utf8");
    assert.equal(body(got), body(want));
  });
});

test("spec fields may carry pre-parsed RawExpr instead of strings", () => {
  const raw = extractRaw("binarySearch.ts");
  const parse = (s: string) => parseExpr(s);
  const walk = (stmts: any[]) => {
    for (const s of stmts) {
      if (s.kind === "while" || s.kind === "forof") {
        s.invariants = s.invariants.map(parse);
        if (s.decreases) s.decreases = parse(s.decreases);
        if (s.doneWith) s.doneWith = parse(s.doneWith);
      }
      for (const k of ["body", "then", "else", "defaultBody"]) if (Array.isArray(s[k])) walk(s[k]);
    }
  };
  for (const fn of raw.functions) {
    fn.requires = fn.requires.map(parse);
    fn.ensures = fn.ensures.map(parse);
    if (fn.decreases) fn.decreases = parse(fn.decreases);
    walk(fn.body);
  }
  withDir(dir => {
    writeFileSync(join(dir, "binarySearch.rawir.json"), JSON.stringify(envelope(raw)));
    const r = lsc(["gen", "--backend=dafny", "binarySearch.rawir.json"], dir);
    assert.equal(r.status, 0, r.stderr);
    const got = readFileSync(join(dir, "binarySearch.dfy.gen"), "utf8");
    const want = readFileSync(join(examples, "binarySearch.dfy.gen"), "utf8");
    assert.equal(body(got), body(want));
  });
});

test("rejects an envelope with an unknown format or version", () => {
  withDir(dir => {
    writeFileSync(join(dir, "bad.rawir.json"), JSON.stringify({ format: "lemmascript-raw-ir", version: 99, module: {} }));
    const r = lsc(["gen", "--backend=dafny", "bad.rawir.json"], dir);
    assert.notEqual(r.status, 0);
    assert.match(r.stderr, /unsupported Raw IR envelope version 99/);
  });
});

// A minimal Raw IR module with one int function `f(a, b) = a <op> b`.
function binopModule(op: string): unknown {
  return {
    file: "ops.py", typeDecls: [], externs: [], constants: [], classes: [],
    functions: [{
      name: "f", exported: true, typeParams: [],
      params: [{ name: "a", tsType: "int" }, { name: "b", tsType: "int" }],
      tsParams: [{ kind: "simple", binds: ["a"] }, { kind: "simple", binds: ["b"] }],
      returnType: "int",
      requires: [{ kind: "binop", op: "!==", left: { kind: "var", name: "b" }, right: { kind: "num", value: 0 } }],
      ensures: [], contract: [], decreases: null, pure: false, autohavoc: false, typeAnnotations: [],
      body: [{ kind: "return", line: 1, value: { kind: "binop", op, left: { kind: "var", name: "a" }, right: { kind: "var", name: "b" } } }],
      line: 1,
    }],
  };
}

test("floordiv lowers to the floored JSFloorDiv helper", () => {
  withDir(dir => {
    writeFileSync(join(dir, "ops.rawir.json"), JSON.stringify(envelope(binopModule("floordiv"))));
    const r = lsc(["gen", "--backend=dafny", "ops.rawir.json"], dir);
    assert.equal(r.status, 0, r.stderr);
    const got = readFileSync(join(dir, "ops.dfy.gen"), "utf8");
    assert.match(got, /function JSFloorDiv\(a: int, b: int\): int/);
    assert.match(got, /JSFloorDiv\(a, b\)/);
  });
});

test("floormod lowers to a FloorMod helper with the divisor's sign", () => {
  withDir(dir => {
    writeFileSync(join(dir, "ops.rawir.json"), JSON.stringify(envelope(binopModule("floormod"))));
    const r = lsc(["gen", "--backend=dafny", "ops.rawir.json"], dir);
    assert.equal(r.status, 0, r.stderr);
    const got = readFileSync(join(dir, "ops.dfy.gen"), "utf8");
    assert.match(got, /function FloorMod\(a: int, b: int\): int/);
    assert.match(got, /FloorMod\(a, b\)/);
    assert.doesNotMatch(got, /JSRem/);
  });
});

test("the frontends config key runs an external command for other extensions", () => {
  withDir(dir => {
    // A stand-in frontend: prints a fixed envelope for whatever file it is given.
    writeFileSync(join(dir, "fake-frontend.mjs"),
      `process.stdout.write(${JSON.stringify(JSON.stringify(envelope(binopModule("floordiv"), { directives: { backend: null, options: {} } })))});\n`);
    writeFileSync(join(dir, "lemmascript.json"), JSON.stringify({ frontends: { ".py": [process.execPath, join(dir, "fake-frontend.mjs")] } }));
    writeFileSync(join(dir, "ops.py"), "# source is opaque to lsc\n");
    const r = lsc(["gen", "--backend=dafny", "ops.py"], dir);
    assert.equal(r.status, 0, r.stderr);
    const got = readFileSync(join(dir, "ops.dfy.gen"), "utf8");
    assert.match(got, /^\/\/ Generated by lsc from ops\.py/m);
    assert.match(got, /JSFloorDiv\(a, b\)/);
  });
});

test("a failing frontend's stderr is surfaced and lsc exits non-zero", () => {
  withDir(dir => {
    writeFileSync(join(dir, "fail.mjs"), `process.stderr.write("ops.py:3: unsupported construct\\n"); process.exit(2);\n`);
    writeFileSync(join(dir, "lemmascript.json"), JSON.stringify({ frontends: { ".py": [process.execPath, join(dir, "fail.mjs")] } }));
    writeFileSync(join(dir, "ops.py"), "\n");
    const r = lsc(["gen", "--backend=dafny", "ops.py"], dir);
    assert.notEqual(r.status, 0);
    assert.match(r.stderr, /ops\.py:3: unsupported construct/);
  });
});
