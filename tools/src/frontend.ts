/**
 * HOOK(external-frontend) — feeding the engine Raw IR from a non-TypeScript
 * frontend.
 *
 * The engine (resolve → narrow → transform → peephole → emit) only needs a
 * `RawModule`. A frontend for another language produces one as JSON, wrapped
 * in a versioned envelope that also carries what `lsc` would otherwise read
 * from `//@ ` directives in the source text:
 *
 *   { "format": "lemmascript-raw-ir", "version": 1,
 *     "producer":   { "name": "...", "version": "..." },        (informational)
 *     "source":     "foo.py",                                  (optional; names the generated header)
 *     "identifiers": ["x", "lo", ...],                          (optional; every source identifier)
 *     "directives": { "backend": null, "options": {...}, "leanModule": null,
 *                     "equality": "structural" },                 (optional; default "reference")
 *     "module":     RawModule }
 *
 * `lsc <cmd> foo.rawir.json` reads an envelope directly. Any other non-TS
 * extension is looked up in the `frontends` key of `lemmascript.json`
 * (`{ ".py": ["cmd", "arg", ...] }`): `lsc` runs the command with the source
 * path appended and reads the envelope from its stdout.
 */

import { existsSync, readFileSync } from "fs";
import { spawnSync } from "child_process";
import path from "path";
import { fileURLToPath } from "url";
import type { RawModule } from "./rawir.js";
import { validateOptions, type ExplicitOptions } from "./config.js";

export const RAW_IR_FORMAT = "lemmascript-raw-ir";
export const RAW_IR_VERSION = 1;
const RAW_IR_SUFFIX = ".rawir.json";
const TS_EXTENSIONS = [".ts", ".tsx", ".mts", ".cts"];

export interface RawIrEnvelope {
  format: typeof RAW_IR_FORMAT;
  version: number;
  producer?: { name: string; version: string };
  source?: string;
  identifiers?: string[];
  directives?: { backend?: string | null; options?: Record<string, unknown>; leanModule?: string | null;
                 equality?: "reference" | "structural" };
  module: RawModule;
}

/** What the engine half of `lsc` needs from any frontend. */
export interface FrontendResult {
  raw: RawModule;
  /** File-level option overrides (the `//@ option` equivalent), validated. */
  fileOptions: ExplicitOptions;
  backend: string | null;
  leanModule: string | undefined;
  /** File name for the generated header (`// Generated by lsc from <name>`). */
  displayName: string;
  /** Names to seed `setUserNames` with. */
  identifiers: Set<string>;
  /** The source language's `==` compares contents (no reference-equality hazard). */
  structuralEquality: boolean;
}

export function isExternalSource(filePath: string): boolean {
  return !TS_EXTENSIONS.some(ext => filePath.endsWith(ext));
}

/** `foo.ts` → `foo`, `foo.py` → `foo`, `foo.rawir.json` → `foo`. */
export function sourceBase(filePath: string): string {
  const name = path.basename(filePath);
  if (name.endsWith(RAW_IR_SUFFIX)) return name.slice(0, -RAW_IR_SUFFIX.length);
  const ext = path.extname(name);
  return ext ? name.slice(0, -ext.length) : name;
}

export function parseEnvelope(text: string, source: string): RawIrEnvelope {
  let parsed: unknown;
  try {
    parsed = JSON.parse(text);
  } catch (err) {
    throw new Error(`${source}: invalid Raw IR JSON (${err instanceof Error ? err.message : String(err)})`);
  }
  const env = parsed as Partial<RawIrEnvelope> | null;
  if (env === null || typeof env !== "object" || env.format !== RAW_IR_FORMAT) {
    throw new Error(`${source}: not a Raw IR envelope (expected "format": "${RAW_IR_FORMAT}")`);
  }
  if (env.version !== RAW_IR_VERSION) {
    throw new Error(`${source}: unsupported Raw IR envelope version ${String(env.version)} (this lsc reads version ${RAW_IR_VERSION})`);
  }
  const m = env.module as Partial<RawModule> | undefined;
  if (!m || typeof m !== "object") throw new Error(`${source}: envelope has no "module"`);
  for (const key of ["typeDecls", "externs", "constants", "functions", "classes"] as const) {
    if (!Array.isArray(m[key])) throw new Error(`${source}: module.${key} must be an array`);
  }
  if (typeof m.file !== "string") throw new Error(`${source}: module.file must be a string`);
  return env as RawIrEnvelope;
}

/** Frontend command for `filePath`'s extension: the config's `frontends` key
 *  first, then the built-in defaults. */
function frontendCommand(filePath: string, frontends: Record<string, string[]>): { argv: string[]; env?: NodeJS.ProcessEnv } | null {
  const ext = path.extname(filePath);
  if (frontends[ext]) return { argv: frontends[ext] };
  return builtinFrontend(ext);
}

/** Built-in frontends shipped alongside this lsc. The Python frontend lives in
 *  `python/` at the repository root; it is used only when present. */
function builtinFrontend(ext: string): { argv: string[]; env: NodeJS.ProcessEnv } | null {
  if (ext !== ".py") return null;
  // tools/src/ (tsx) and tools/dist/ (built) both sit two levels below the root.
  const pythonDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..", "python");
  if (!existsSync(path.join(pythonDir, "lemmascript_python"))) return null;
  const pythonPath = [pythonDir, process.env.PYTHONPATH].filter(Boolean).join(path.delimiter);
  return {
    argv: [process.env.LSC_PYTHON ?? "python3", "-m", "lemmascript_python", "extract"],
    env: { ...process.env, PYTHONPATH: pythonPath },
  };
}

export function loadExternalSource(absPath: string, frontends: Record<string, string[]>): FrontendResult {
  let envelope: RawIrEnvelope;
  let displayName = path.basename(absPath);
  if (absPath.endsWith(RAW_IR_SUFFIX)) {
    envelope = parseEnvelope(readFileSync(absPath, "utf8"), absPath);
    if (envelope.source) displayName = path.basename(envelope.source);
  } else {
    const cmd = frontendCommand(absPath, frontends);
    if (!cmd) {
      throw new Error(`${absPath}: no frontend for '${path.extname(absPath)}' files `
        + `(add it to "frontends" in lemmascript.json, e.g. { "frontends": { "${path.extname(absPath)}": ["my-frontend", "extract"] } })`);
    }
    const [bin, ...args] = cmd.argv;
    const r = spawnSync(bin, [...args, absPath], { encoding: "utf8", env: cmd.env ?? process.env, maxBuffer: 256 * 1024 * 1024 });
    if (r.error) throw new Error(`${absPath}: could not run frontend '${bin}': ${r.error.message}`);
    if (r.status !== 0) {
      const detail = (r.stderr || r.stdout || "").trim();
      throw new Error(`${absPath}: frontend '${cmd.argv.join(" ")}' failed (exit ${r.status})${detail ? `\n${detail}` : ""}`);
    }
    envelope = parseEnvelope(r.stdout, `${absPath} (frontend output)`);
  }
  const d = envelope.directives ?? {};
  return {
    raw: envelope.module,
    fileOptions: validateOptions(d.options ?? {}, `${absPath} (frontend directives)`),
    backend: d.backend ?? null,
    leanModule: d.leanModule ?? undefined,
    displayName,
    identifiers: collectIdentifiers(envelope.module, envelope.identifiers ?? []),
    structuralEquality: d.equality === "structural",
  };
}

/** Every identifier-like name in a Raw IR module, for `setUserNames`: the TS
 *  extractor seeds it from source tokens; for an external module the names
 *  the engine must not collide with all appear in the IR (or its spec text). */
export function collectIdentifiers(raw: RawModule, extra: string[] = []): Set<string> {
  const names = new Set<string>(extra);
  const ident = /^[A-Za-z_$][\w$]*$/;
  const visit = (v: unknown, key: string): void => {
    if (typeof v === "string") {
      if (["name", "names", "target", "field", "var", "qualified", "flat"].includes(key) && ident.test(v)) names.add(v);
      else if (["requires", "ensures", "invariants", "decreases", "doneWith", "init", "value", "expr"].includes(key)) {
        for (const m of v.matchAll(/[A-Za-z_$][\w$]*/g)) names.add(m[0]);
      }
      return;
    }
    if (Array.isArray(v)) { for (const x of v) visit(x, key); return; }
    if (v && typeof v === "object") for (const [k, x] of Object.entries(v)) visit(x, k);
  };
  visit(raw, "");
  return names;
}
